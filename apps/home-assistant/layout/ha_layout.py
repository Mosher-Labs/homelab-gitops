"""Keep Home Assistant's floors, areas, device names and entity IDs in git.

Usage:
  uv run --with websockets==15.0.1 --with pyyaml==6.0.3 ha_layout.py export
  uv run --with websockets==15.0.1 --with pyyaml==6.0.3 ha_layout.py apply [--apply]

export  writes layout.yaml from the running Home Assistant.
apply   makes Home Assistant match layout.yaml. It is a dry run that prints
        each change unless you pass --apply.

Devices are matched by their MAC addresses and integration identifiers, and
entities by domain, platform and unique ID, so after a rebuild and a fresh pairing
everything goes back to the same room and name. Nothing secret is stored:
no tokens, passwords or pairing keys, only names, rooms and hardware IDs.

Needs HA_URL (default http://192.168.87.10:8123) and a long-lived token in
HA_TOKEN or in the file named by HA_TOKEN_FILE (default ~/.config/ha/token).
"""
import asyncio
import json
import os
import pathlib
import sys

import websockets
import yaml

HERE = pathlib.Path(__file__).resolve().parent
LAYOUT = HERE / 'layout.yaml'
HA_URL = os.environ.get('HA_URL', 'http://192.168.87.10:8123')


def token():
    if os.environ.get('HA_TOKEN'):
        return os.environ['HA_TOKEN']
    path = os.environ.get('HA_TOKEN_FILE', '~/.config/ha/token')
    return pathlib.Path(path).expanduser().read_text().strip()


class HA:
    def __init__(self, ws):
        self.ws, self.n = ws, 0

    async def call(self, msg_type, **data):
        self.n += 1
        await self.ws.send(json.dumps({'id': self.n, 'type': msg_type, **data}))
        while True:
            r = json.loads(await self.ws.recv())
            if r.get('id') == self.n and r.get('type') == 'result':
                break
        if not r['success']:
            raise RuntimeError(f'{msg_type} {data}: {r.get("error")}')
        return r['result']


async def connect():
    ws = await websockets.connect(HA_URL.replace('http', 'ws', 1) + '/api/websocket', max_size=None)
    await ws.recv()
    await ws.send(json.dumps({'type': 'auth', 'access_token': token()}))
    if json.loads(await ws.recv())['type'] != 'auth_ok':
        sys.exit('Home Assistant rejected the token')
    return ws, HA(ws)


async def registries(ha):
    return (await ha.call('config/floor_registry/list'),
            await ha.call('config/area_registry/list'),
            await ha.call('config/device_registry/list'),
            await ha.call('config/entity_registry/list'))


class Indented(yaml.SafeDumper):
    """Indent list items under their key, the way yamllint expects."""

    def increase_indent(self, flow=False, indentless=False):
        return super().increase_indent(flow, False)


def keys(dev):
    """Stable keys for a device: its MACs and its integration identifiers."""
    return ({f'{t}:{v}'.lower() for t, v in dev.get('connections', [])}
            | {f'{d}:{v}' for d, v in dev.get('identifiers', [])})


async def export():
    ws, ha = await connect()
    floors, areas, devices, entities = await registries(ha)
    await ws.close()
    area_name = {a['area_id']: a['name'] for a in areas}
    floor_name = {f['floor_id']: f['name'] for f in floors}
    dev_out, dev_ids = [], {}
    for d in sorted(devices, key=lambda d: (d['name_by_user'] or d['name'] or '')):
        if d.get('entry_type') == 'service' or not keys(d):
            continue
        item = {'match': sorted(keys(d)), 'model': d.get('model')}
        if d['name_by_user']:
            item['name'] = d['name_by_user']
        else:
            item['default_name'] = d['name']
        if d['area_id']:
            item['area'] = area_name[d['area_id']]
        if d['disabled_by'] == 'user':
            item['disabled'] = True
        dev_out.append(item)
        dev_ids[d['id']] = True
    ent_out = []
    for e in sorted(entities, key=lambda e: e['entity_id']):
        if e['device_id'] not in dev_ids:
            continue
        item = {'platform': e['platform'], 'unique_id': e['unique_id'], 'entity_id': e['entity_id']}
        if e.get('name'):
            item['name'] = e['name']
        if e.get('area_id'):
            item['area'] = area_name[e['area_id']]
        if e.get('disabled_by') == 'user':
            item['disabled'] = True
        ent_out.append(item)
    layout = {
        'floors': [{'name': f['name'], 'level': f['level']} for f in sorted(floors, key=lambda f: f['level'] or 0)],
        'areas': [{'name': a['name'], **({'floor': floor_name[a['floor_id']]} if a['floor_id'] else {})}
                  for a in sorted(areas, key=lambda a: a['name'])],
        'devices': dev_out,
        'entities': ent_out,
    }
    header = ('# Generated by ha_layout.py export. Edit it, then run ha_layout.py apply.\n'
              '# yamllint disable rule:line-length\n')
    LAYOUT.write_text(header + yaml.dump(layout, Dumper=Indented, sort_keys=False,
                                         allow_unicode=True, width=100))
    print(f'wrote {LAYOUT}: {len(layout["floors"])} floors, {len(layout["areas"])} areas, '
          f'{len(dev_out)} devices, {len(ent_out)} entities')


async def apply(do_it):
    want = yaml.safe_load(LAYOUT.read_text())
    ws, ha = await connect()
    floors, areas, devices, entities = await registries(ha)
    say = (lambda m: print('apply: ' + m)) if do_it else (lambda m: print('would: ' + m))

    floor_id = {f['name']: f['floor_id'] for f in floors}
    for f in want['floors']:
        if f['name'] not in floor_id:
            say(f'create floor {f["name"]}')
            if do_it:
                floor_id[f['name']] = (await ha.call('config/floor_registry/create', name=f['name'],
                                                     level=f.get('level')))['floor_id']
    area_id = {a['name']: a['area_id'] for a in areas}
    area_floor = {a['name']: a['floor_id'] for a in areas}
    for a in want['areas']:
        fid = floor_id.get(a.get('floor')) if a.get('floor') else None
        if a['name'] not in area_id:
            say(f'create area {a["name"]} on {a.get("floor")}')
            if do_it:
                area_id[a['name']] = (await ha.call('config/area_registry/create', name=a['name'],
                                                    floor_id=fid))['area_id']
        elif area_floor[a['name']] != fid:
            say(f'move area {a["name"]} to floor {a.get("floor")}')
            if do_it:
                await ha.call('config/area_registry/update', area_id=area_id[a['name']], floor_id=fid)

    by_key = {}
    for d in devices:
        for k in keys(d):
            by_key[k] = d
    missing = 0
    for w in want['devices']:
        d = next((by_key[k] for k in w['match'] if k in by_key), None)
        label = w.get('name') or w.get('default_name')
        if not d:
            missing += 1
            print(f'not in Home Assistant yet: {label}')
            continue
        change = {}
        if w.get('name') and d['name_by_user'] != w['name']:
            change['name_by_user'] = w['name']
        aid = area_id.get(w['area']) if w.get('area') else None
        if w.get('area') and d['area_id'] != aid:
            change['area_id'] = aid
        if w.get('disabled') and d['disabled_by'] != 'user':
            change['disabled_by'] = 'user'
        if change:
            say(f'device {label}: {change}')
            if do_it:
                await ha.call('config/device_registry/update', device_id=d['id'], **change)

    # A unique ID is only unique within one domain and platform (a Ring
    # camera's light and siren share one), so match on all three.
    current = {(e['entity_id'].split('.')[0], e['platform'], e['unique_id']): e for e in entities}
    for w in want['entities']:
        e = current.get((w['entity_id'].split('.')[0], w['platform'], w['unique_id']))
        if not e:
            continue
        change = {}
        if e['entity_id'] != w['entity_id']:
            change['new_entity_id'] = w['entity_id']
        if w.get('name') and e.get('name') != w['name']:
            change['name'] = w['name']
        if w.get('area') and e.get('area_id') != area_id.get(w['area']):
            change['area_id'] = area_id.get(w['area'])
        if w.get('disabled') and e.get('disabled_by') != 'user':
            change['disabled_by'] = 'user'
        if change:
            say(f'entity {e["entity_id"]}: {change}')
            if do_it:
                await ha.call('config/entity_registry/update', entity_id=e['entity_id'], **change)
    await ws.close()
    if missing:
        print(f'{missing} device(s) in layout.yaml are not paired yet; run apply again after pairing them')


if __name__ == '__main__':
    cmd = sys.argv[1] if len(sys.argv) > 1 else ''
    if cmd == 'export':
        asyncio.run(export())
    elif cmd == 'apply':
        asyncio.run(apply('--apply' in sys.argv))
    else:
        sys.exit(__doc__)
